"""
Benchmark Report HTML & Visualization Exporter
"""
import json
import os
import sys
from datetime import datetime

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "../..")))
from tests.evaluation.run_evaluations import EvaluationSuite

def generate_html_report(results: dict) -> str:
    metrics = results.get("metrics", {})
    scenarios = results.get("scenarios", [])
    
    rows = ""
    for s in scenarios:
        status_color = "#10b981" if s["passed"] else "#f43f5e"
        badge = "PASS" if s["passed"] else "FAIL"
        rows += f"""
        <tr style="border-bottom: 1px solid #1e293b;">
            <td style="padding: 10px 14px; font-family: monospace; color: #38bdf8;">{s['code']}</td>
            <td style="padding: 10px 14px; color: #cbd5e1;">{s['title']}</td>
            <td style="padding: 10px 14px; text-align: right;">
                <span style="background: {status_color}22; color: {status_color}; border: 1px solid {status_color}44; padding: 3px 8px; border-radius: 9999px; font-weight: bold; font-size: 11px;">
                    {badge}
                </span>
            </td>
        </tr>
        """

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <title>LocalCompute Commons - Benchmark Evaluation Report</title>
    <style>
        body {{ background: #0b0f19; color: #f8fafc; font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif; padding: 40px 20px; }}
        .container {{ max-width: 900px; margin: 0 auto; }}
        .card {{ background: #111827; border: 1px solid #1f2937; border-radius: 16px; padding: 24px; margin-bottom: 24px; }}
        .grid {{ display: grid; grid-template-columns: repeat(auto-fit, minmax(200px, 1fr)); gap: 16px; margin-bottom: 24px; }}
        .stat {{ background: #1e293b; border: 1px solid #334155; border-radius: 12px; padding: 16px; text-align: center; }}
        .stat-val {{ font-size: 28px; font-weight: 800; color: #38bdf8; margin-top: 4px; }}
        .stat-lbl {{ font-size: 11px; text-transform: uppercase; color: #94a3b8; font-weight: 600; letter-spacing: 0.05em; }}
        table {{ width: 100%; border-collapse: collapse; text-align: left; font-size: 13px; }}
        th {{ background: #1e293b; color: #94a3b8; padding: 12px 14px; font-size: 11px; text-transform: uppercase; }}
    </style>
</head>
<body>
    <div class="container">
        <h1 style="font-size: 24px; font-weight: 800; margin-bottom: 8px;">LocalCompute Commons: 40-Scenario Benchmark Report</h1>
        <p style="color: #94a3b8; font-size: 13px; margin-bottom: 24px;">Deterministic Scheduling, Fault Recovery, and Privacy Perimeter Validation Results</p>

        <div class="grid">
            <div class="stat">
                <div class="stat-lbl">Scheduling Correctness</div>
                <div class="stat-val">{metrics.get('scheduling_correctness_pct')}%</div>
            </div>
            <div class="stat">
                <div class="stat-lbl">Task Completion Rate</div>
                <div class="stat-val">{metrics.get('task_completion_rate_pct')}%</div>
            </div>
            <div class="stat">
                <div class="stat-lbl">Avg Recovery Latency</div>
                <div class="stat-val">{metrics.get('avg_recovery_time_sec')}s</div>
            </div>
            <div class="stat">
                <div class="stat-lbl">P95 Scheduler Latency</div>
                <div class="stat-val">{metrics.get('p95_latency_ms')} ms</div>
            </div>
        </div>

        <div class="card">
            <h2 style="font-size: 16px; font-weight: 700; margin-top: 0; margin-bottom: 16px;">Detailed Scenario Execution Results</h2>
            <table>
                <thead>
                    <tr>
                        <th>Code</th>
                        <th>Scenario Description</th>
                        <th style="text-align: right;">Result</th>
                    </tr>
                </thead>
                <tbody>
                    {rows}
                </tbody>
            </table>
        </div>
        <p style="text-align: center; color: #64748b; font-size: 11px;">Generated by LocalCompute Commons Automated Test Harness at {datetime.utcnow().isoformat()}Z</p>
    </div>
</body>
</html>
"""

async def main():
    suite = EvaluationSuite()
    results = await suite.run_all()
    html = generate_html_report(results)
    out_path = os.path.abspath("benchmark_report.html")
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(html)
    print(f"\n✓ Generated Visual HTML Benchmark Report: {out_path}")

if __name__ == "__main__":
    import asyncio
    asyncio.run(main())
